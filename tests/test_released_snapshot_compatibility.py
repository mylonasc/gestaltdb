"""Load sampler snapshots produced by pinned released wheels.

The rest of the sampler suite builds a snapshot with the working tree and then
downgrades it to look like an old release. That exercises the legacy branches
but cannot prove that bytes written by an older release still load. The frozen
artifacts in ``tests/fixtures/released_snapshots`` were generated by:

- ``gestaltdb 0.10.2`` -> dense format v1
- ``gestaltdb 0.12.1`` -> dense format v2 and temporal format v2

``expected.json`` records the writer version, the seeded sampling results
produced by that wheel, and a SHA-256 for every fixture file. Regenerate with
``tests/fixtures/released_snapshots/generate.py`` only when the declared
compatibility range changes; do not rewrite the artifacts from the working
tree.
"""

import hashlib
import json
from pathlib import Path

import pytest

from gestaltdb import SamplerEngine, SamplerSnapshot, TemporalContext

FIXTURE_ROOT = Path(__file__).parent / "fixtures" / "released_snapshots"
EXPECTED = json.loads((FIXTURE_ROOT / "expected.json").read_text())

PINNED = {
    "dense_v1": ("0.10.2", 1),
    "dense_v2": ("0.12.1", 2),
    "temporal_v2": ("0.12.1", 2),
}


def _expected(name):
    return EXPECTED["fixtures"][name]


def _assert_neighbors(result, expected):
    assert result.input_nodes.tolist() == expected["input_nodes"]
    assert result.edge_indices.tolist() == expected["edge_indices"]
    assert result.neighbor_nodes.tolist() == expected["neighbor_nodes"]


@pytest.mark.parametrize("name", sorted(PINNED))
def test_released_fixture_bytes_match_their_recorded_provenance(name):
    expected = _expected(name)
    version, format_version = PINNED[name]
    assert expected["gestaltdb_version"] == version
    assert expected["format_version"] == format_version
    actual = {
        path.relative_to(FIXTURE_ROOT / name).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted((FIXTURE_ROOT / name).rglob("*")) if path.is_file()
    }
    assert actual == expected["files"]


@pytest.mark.parametrize("name", ["dense_v1", "dense_v2"])
@pytest.mark.parametrize("mmap", [False, True], ids=["ram", "memmap"])
def test_dense_released_snapshot_loads_and_reproduces_seeded_samples(name, mmap):
    expected = _expected(name)
    snapshot = SamplerSnapshot.load(FIXTURE_ROOT / name, mmap=mmap)

    assert snapshot.metadata["format_version"] == expected["format_version"]
    assert snapshot.temporal is False
    assert snapshot.num_nodes == expected["num_nodes"]
    assert snapshot.num_edges == expected["num_edges"]
    assert snapshot.num_relations == expected["num_relations"]
    # Legacy v1 fixtures omit lookup arrays; load must derive them.
    assert snapshot.node_int("n0") == 0
    assert snapshot.node_int("n5") == 5
    assert snapshot.edge_int("e0") == 0
    assert snapshot.edge_int("e7") == 7
    assert snapshot.relation_int("KNOWS") == 0
    assert snapshot.relation_int("WORKS_AT") == 1

    engine = SamplerEngine.load(FIXTURE_ROOT / name, mode="memmap" if mmap else "ram", seed=7)
    _assert_neighbors(engine.sample_neighbors([0, 1], fanout=2, direction="out"),
                      expected["sampled"])
    _assert_neighbors(
        engine.sample_neighbors(
            [0], fanout=2, direction="out",
            relations=[snapshot.relation_int("WORKS_AT")]),
        expected["relation_filtered"],
    )


@pytest.mark.parametrize("mmap", [False, True], ids=["ram", "memmap"])
def test_temporal_released_snapshot_preserves_half_open_history(mmap):
    expected = _expected("temporal_v2")
    snapshot = SamplerSnapshot.load(FIXTURE_ROOT / "temporal_v2", mmap=mmap)

    assert snapshot.metadata["format_version"] == expected["format_version"]
    assert snapshot.temporal is True
    assert snapshot.num_nodes == expected["num_nodes"]
    assert len(snapshot.edge_version_ids) == expected["num_edge_versions"]
    assert snapshot.metadata["temporal_encoding"]["time_bucket"] == "day"
    assert snapshot.metadata["temporal_encoding"]["interval"] == "half_open"

    engine = SamplerEngine.load(
        FIXTURE_ROOT / "temporal_v2", mode="memmap" if mmap else "ram", seed=7)
    contexts = {
        "at_50": TemporalContext.as_of(50),
        "at_100": TemporalContext.as_of(100),
        "at_150": TemporalContext.as_of(150),
        "at_200": TemporalContext.as_of(200),
        "window_120_160": TemporalContext.during(120, 160),
    }
    for label, context in contexts.items():
        result = engine.sample_neighbors(
            [0], fanout=10, direction="out", temporal=context)
        _assert_neighbors(result, expected["cases"][label])
        assert [str(item) for item in result.edge_version_ids] == (
            expected["cases"][label]["edge_version_ids"])

    # The correction at 100 is a half-open boundary: the old e0 version is
    # gone, the new one is visible, and e2's [50, 150) window still is.
    assert expected["cases"]["at_50"]["neighbor_nodes"] == [1, 2, 3]
    assert expected["cases"]["at_100"]["neighbor_nodes"] == [2, 1, 3]
    assert expected["cases"]["at_200"]["edge_indices"] == []
